"""Instruction assembly for the assistant's workspace.

Claude Code reads ``CLAUDE.md`` in the working directory. We generate it from
three layers so the assistant always knows where it is and what it may touch:

1. the Lyndrix base instructions (this file — what Lyndrix is, how plugins and
   the API fit together, house rules),
2. one file per loaded plugin that declares ``ai_instructions`` in its manifest
   (``.lyndrix/instructions/<plugin_id>.md``, pulled in with Claude Code's
   ``@path`` import syntax), so every plugin describes itself in its own words,
3. an operator addendum (plugin setting ``extra_instructions``).

Regenerated on every workspace sync and whenever the plugin set changes.
"""
from __future__ import annotations

import re
from datetime import datetime, timezone
from pathlib import Path
from typing import Iterable

from core.api import get_logger

log = get_logger("Plugin:AI:Instructions")

INSTRUCTIONS_DIR = Path(".lyndrix") / "instructions"
_PLUGIN_FILE_RE = re.compile(r"[^A-Za-z0-9_.-]+")

BASE_INSTRUCTIONS = """# Lyndrix AI Assistant — workspace instructions

You are the AI assistant embedded in **Lyndrix**, a modular operations platform
(Python/FastAPI core with a React shell and plugins). You run inside a sandboxed
container next to a Lyndrix instance; this directory is your working repository.

## What Lyndrix is
- The **core** boots plugins, hosts the REST API under `/api/...`, the React shell,
  identity & permissions (roles, groups, per-plugin grants), notifications, a
  cluster layer (several instances share one database and Vault) and theming.
- **Plugins** add capabilities: each one has a stable id (`lyndrix.plugin.<name>`),
  a REST router at `/api/plugins/<id>/…`, optional React routes, settings stored
  in Vault and declared permissions. The plugin files in `.lyndrix/instructions/`
  describe the plugins that are currently installed — read them when a question
  touches that area.
- The platform language is **German** for operators and documentation; code,
  identifiers and commit messages are **English**. Answer in the language the
  user writes in.

## House rules
- Prefer the documented APIs over guessing internals; when something is unclear,
  say so and propose how to verify it.
- Never print or store credentials, tokens or Vault contents. Configuration values
  that look like secrets are redacted on purpose.
- Changes to files in this workspace are fine; everything outside the workspace
  is out of reach by design. Do not try to work around the sandbox.
- Be concise. Lead with the answer, then the reasoning that matters.

## Imported plugin instructions
"""


def plugin_instruction_filename(plugin_id: str) -> str:
    return _PLUGIN_FILE_RE.sub("_", plugin_id) + ".md"


def write_instructions(
    workspace: Path,
    plugin_instructions: Iterable[tuple[str, str, str]],
    extra: str | None = None,
) -> dict:
    """Write ``CLAUDE.md`` and the per-plugin files; returns a small summary.

    ``plugin_instructions`` yields ``(plugin_id, plugin_name, markdown)``.
    Files of plugins that no longer provide instructions are removed so the
    import list and the directory never drift apart.
    """
    workspace = Path(workspace)
    inst_dir = workspace / INSTRUCTIONS_DIR
    inst_dir.mkdir(parents=True, exist_ok=True)

    kept: set[str] = set()
    imports: list[str] = []
    for plugin_id, plugin_name, markdown in sorted(plugin_instructions, key=lambda t: t[0]):
        text = (markdown or "").strip()
        if not text:
            continue
        fname = plugin_instruction_filename(plugin_id)
        body = f"# {plugin_name} (`{plugin_id}`)\n\n{text}\n"
        (inst_dir / fname).write_text(body, encoding="utf-8")
        kept.add(fname)
        imports.append(f"- {plugin_name}: @{INSTRUCTIONS_DIR.as_posix()}/{fname}")
    for stale in inst_dir.glob("*.md"):
        if stale.name not in kept:
            stale.unlink(missing_ok=True)

    parts = [BASE_INSTRUCTIONS.rstrip("\n")]
    parts.append("\n".join(imports) if imports else "_No plugin provides instructions yet._")
    if extra and extra.strip():
        parts.append("\n## Operator notes\n\n" + extra.strip())
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    parts.append(f"\n<!-- generated by lyndrix-plugin-ai-assistant on {stamp}; edit the plugin manifests, not this file -->\n")
    (workspace / "CLAUDE.md").write_text("\n".join(parts), encoding="utf-8")
    log.info(f"Instructions written: {len(kept)} plugin file(s), extra={'yes' if extra else 'no'}")
    return {"plugins": sorted(kept), "has_extra": bool(extra and extra.strip())}


def collect_plugin_instructions() -> list[tuple[str, str, str]]:
    """``(plugin_id, name, ai_instructions)`` of every loaded plugin that has them.

    Uses the read-only registry view of core API 1.11 and falls back to the
    manager on older cores (read access only — never mutate the registry).
    """
    manifests = []
    try:
        from core.api import module_registry  # type: ignore[attr-defined]

        manifests = list(module_registry.get_manifests())
    except Exception:
        try:
            from core.components.plugins.logic.manager import module_manager

            manifests = list(module_manager.get_manifests())
        except Exception as exc:
            log.debug(f"Instructions: no manifest access ({exc})")
    out = []
    for m in manifests:
        text = getattr(m, "ai_instructions", None)
        if text and getattr(m, "type", "PLUGIN") == "PLUGIN":
            out.append((str(m.id), str(getattr(m, "name", m.id)), str(text)))
    return out
