"""The assistant's working repository on the shared storage.

``STORAGE_DIR/ai_workspace/repo`` is a git repository the runner container
mounts at ``/workspace``. It always exists locally (``git init`` on first use);
when the operator configures ``workspace_repo_url`` it is cloned from / pulled
against that remote (token-authenticated for private repositories, the token is
never written to disk — it travels in the URL of the one git command only).
``CLAUDE.md`` and ``.lyndrix/instructions/`` are regenerated on every sync.

All functions are blocking (git subprocesses) — call them via ``asyncio.to_thread``.
"""
from __future__ import annotations

import os
import subprocess
from datetime import datetime, timezone
from pathlib import Path
from typing import Optional

from core.api import get_logger

from .instructions import collect_plugin_instructions, write_instructions

log = get_logger("Plugin:AI:Workspace")

GIT_TIMEOUT_S = 120


def _git(repo: Path, *args: str, timeout: int = GIT_TIMEOUT_S) -> subprocess.CompletedProcess:
    return subprocess.run(
        ["git", "-C", str(repo), *args],
        capture_output=True, text=True, timeout=timeout, check=False,
        env={"GIT_TERMINAL_PROMPT": "0", "HOME": str(repo.parent), "PATH": "/usr/bin:/bin:/usr/local/bin"},
    )


def _with_token(url: str, token: Optional[str]) -> str:
    """``https://TOKEN@host/path`` for a private remote; untouched otherwise."""
    if not token or not url.startswith("https://") or "@" in url.split("//", 1)[1].split("/", 1)[0]:
        return url
    return url.replace("https://", f"https://{token}@", 1)


class WorkspaceManager:
    def __init__(self, storage_dir: Path) -> None:
        self.root = Path(storage_dir) / "ai_workspace"
        self.repo = self.root / "repo"
        self.last_sync: Optional[datetime] = None
        self.last_error: Optional[str] = None

    # ------------------------------------------------------------------ state

    def status(self) -> dict:
        exists = (self.repo / ".git").is_dir()
        remote = branch = None
        dirty = 0
        if exists:
            r = _git(self.repo, "remote", "get-url", "origin", timeout=10)
            remote = r.stdout.strip() if r.returncode == 0 else None
            if remote and "@" in remote:   # never show a token that an operator pasted into the URL
                remote = "https://" + remote.split("@", 1)[1]
            b = _git(self.repo, "rev-parse", "--abbrev-ref", "HEAD", timeout=10)
            branch = b.stdout.strip() if b.returncode == 0 else None
            s = _git(self.repo, "status", "--porcelain", timeout=20)
            dirty = len([ln for ln in s.stdout.splitlines() if ln.strip()]) if s.returncode == 0 else 0
        return {
            "path": str(self.repo),
            "initialized": exists,
            "remote": remote,
            "branch": branch,
            "dirty_files": dirty,
            "has_instructions": (self.repo / "CLAUDE.md").is_file(),
            "last_sync": self.last_sync.isoformat() if self.last_sync else None,
            "last_error": self.last_error,
        }

    # ------------------------------------------------------------------ sync

    def sync(self, *, repo_url: Optional[str], branch: str, token: Optional[str],
             extra_instructions: Optional[str]) -> dict:
        """Make the repository exist and current, then regenerate the instructions."""
        self.last_error = None
        try:
            self.root.mkdir(parents=True, exist_ok=True)
            if repo_url:
                self._sync_remote(repo_url.strip(), branch or "main", token)
            elif not (self.repo / ".git").is_dir():
                self.repo.mkdir(parents=True, exist_ok=True)
                self._check(_git(self.repo, "init", "-q", "-b", branch or "main"), "git init")
                _git(self.repo, "config", "user.email", "lyndrix-ai@localhost")
                _git(self.repo, "config", "user.name", "Lyndrix AI Assistant")
                (self.repo / "README.md").write_text(
                    "# Lyndrix AI workspace\n\nWorking repository of the Lyndrix AI assistant. "
                    "`CLAUDE.md` and `.lyndrix/instructions/` are generated by the plugin.\n",
                    encoding="utf-8",
                )
            summary = write_instructions(self.repo, collect_plugin_instructions(), extra_instructions)
            self.ensure_agent_access()
            self.last_sync = datetime.now(timezone.utc)
            return {"ok": True, **summary, **self.status()}
        except Exception as exc:  # noqa: BLE001 — surfaced in the status, never raised into setup()
            self.last_error = str(exc)[:500]
            log.error(f"Workspace sync failed: {exc}")
            return {"ok": False, "error": self.last_error, **self.status()}

    def _sync_remote(self, repo_url: str, branch: str, token: Optional[str]) -> None:
        url = _with_token(repo_url, token)
        if not (self.repo / ".git").is_dir():
            if self.repo.exists() and any(self.repo.iterdir()):
                raise RuntimeError(f"{self.repo} exists but is not a git repository")
            self.repo.parent.mkdir(parents=True, exist_ok=True)
            res = subprocess.run(
                ["git", "clone", "-q", "--branch", branch, "--single-branch", url, str(self.repo)],
                capture_output=True, text=True, timeout=GIT_TIMEOUT_S, check=False,
                env={"GIT_TERMINAL_PROMPT": "0", "HOME": str(self.root), "PATH": "/usr/bin:/bin:/usr/local/bin"},
            )
            self._check(res, "git clone")
            _git(self.repo, "config", "user.email", "lyndrix-ai@localhost")
            _git(self.repo, "config", "user.name", "Lyndrix AI Assistant")
        else:
            # Keep the stored remote token-free; authenticate per command.
            _git(self.repo, "remote", "set-url", "origin", repo_url)
            self._check(_git(self.repo, "fetch", "-q", url, branch), "git fetch")
            status = _git(self.repo, "status", "--porcelain", timeout=20).stdout.strip()
            if status:
                log.warning("Workspace has uncommitted changes — remote update not merged (fast-forward skipped).")
            else:
                self._check(_git(self.repo, "merge", "-q", "--ff-only", "FETCH_HEAD"), "git merge --ff-only")

    @staticmethod
    def _check(res: subprocess.CompletedProcess, what: str) -> None:
        if res.returncode != 0:
            detail = (res.stderr or res.stdout or "").strip()
            # a pasted token must never end up in logs or the UI
            raise RuntimeError(f"{what} failed: {detail.split('@')[-1][:300] if '://' in detail else detail[:300]}")

    def regenerate_instructions(self, extra_instructions: Optional[str]) -> dict:
        if not (self.repo / ".git").is_dir():
            return {"ok": False, "error": "workspace not initialized"}
        summary = write_instructions(self.repo, collect_plugin_instructions(), extra_instructions)
        self.ensure_agent_access()
        return {"ok": True, **summary}

    def ensure_agent_access(self, uid: int = 10000, gid: int = 10000) -> None:
        """The runner container works as user ``agent`` (uid/gid 10000); the core
        creates the files as root. Hand the tree over when we may (root), otherwise
        fall back to group/world-writable bits so the agent can still edit."""
        if not self.root.exists():
            return
        try:
            if os.geteuid() == 0:
                for dirpath, dirnames, filenames in os.walk(self.root):
                    os.chown(dirpath, uid, gid)
                    for name in filenames:
                        try:
                            os.chown(os.path.join(dirpath, name), uid, gid)
                        except OSError:
                            pass
                return
        except OSError as exc:
            log.warning(f"Workspace chown to {uid}:{gid} failed ({exc}); falling back to permission bits.")
        for dirpath, dirnames, filenames in os.walk(self.root):
            try:
                os.chmod(dirpath, 0o2777)
                for name in filenames:
                    os.chmod(os.path.join(dirpath, name), 0o666)
            except OSError:
                pass

    def read_instructions(self) -> str:
        p = self.repo / "CLAUDE.md"
        return p.read_text(encoding="utf-8") if p.is_file() else ""
